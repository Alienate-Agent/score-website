import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
import {searchTerms} from '../lib/search-excerpt.ts';
const source=fs.readFileSync(new URL('../lib/site-search.ts',import.meta.url),'utf8');
const output={exports:{}};
vm.runInNewContext(ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText,{module:output,exports:output.exports,URL,require:id=>{assert.equal(id,'./search-excerpt');return {searchTerms};}});
const {sitePagePath,searchSite,siteSearchStarts}=output.exports;
const base='https://example.test/studio/tidemark/index.html';
assert.equal(sitePagePath('town.html#square',base),'/studio/tidemark/town.html');
assert.equal(sitePagePath('/agent-guide#guide-return',base),'/agent-guide');
for(const path of ['https://other.test/','/api/board-search?q=secret','/board?kind=post&id=1','/agent-words?agent=tidemark','/records/private.json','/type-study.html','/private/report.html','/studio/tidemark/../../private.html','/charter?foo=bar'])assert.equal(sitePagePath(path,base),null,path);
const credentialUrl=new URL(base);credentialUrl.username='fixture';credentialUrl.password='fixture';
assert.equal(sitePagePath(credentialUrl.href,base),null);
assert.ok(siteSearchStarts.includes('/lens/index.html')&&siteSearchStarts.includes('/'));
const records=[{href:'/agent-guide#guide-return',page:'Campaign companion',title:'Scheduled runs',body:'Keep context and manage costs.'},{href:'/#story-beginning',page:'The story',title:'The artist discovers a board',body:'The treasury has money. Scheduled runs come later.'}];
assert.equal(searchSite(records,'scheduled')[0].href,'/agent-guide#guide-return');
assert.equal(searchSite(records,'treasury')[0].href,'/#story-beginning');
assert.equal(searchSite(records,'SChÉDuled costs').length,1);
assert.equal(searchSite(records,'').length,0);
assert.equal(searchSite(records,'xyzzy').length,0);
assert.ok(source.includes('script,style,template')&&source.includes('[data-redaction-id]')&&source.includes('#all-record-search'));
console.log('PASS: public-page allowlist, cross-host/API/private/query exclusions, multi-term Unicode site matching, title ranking and extraction exclusions. Browser extraction checked separately.');
