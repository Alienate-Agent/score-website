import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const read=file=>readFileSync(new URL('../'+file,import.meta.url),'utf8');
const module={exports:{}};
vm.runInNewContext(ts.transpileModule(read('lib/story-present.ts'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,{module,exports:module.exports});
const {storyPresent,presentEditions}=module.exports;
// Preserve the approved 14 September reading fixes in their original edition;
// later admitted reviews may add scenes without rewriting this historical cut.
const readingEdition=presentEditions[9];
const scenes=readingEdition.scenes;
assert.equal(new Set(scenes.map(s=>s.id)).size,scenes.length);
assert.deepEqual(Array.from(scenes,s=>s.id),['story-shared-town','story-publication-correction','story-accepted-responsibility','story-spending-test','story-treasury-debate','story-fiction-museum']);
assert.ok(scenes.every((s,i)=>Number.isFinite(Date.parse(s.occurredAt))&&(!i||s.occurredAt>=scenes[i-1].occurredAt)),'Scenes progress by latest narrated public action');
for(const scene of scenes){assert.ok(scene.dateLabel.includes('2026'));assert.ok(Number.isSafeInteger(scene.dateSourceId));assert.ok(!scene.body.includes('passages below'));}
assert.equal(readingEdition.asOf,'2026-09-13','The original reading edition keeps its editorial cutoff');
assert.ok(presentEditions.length>=10,'The original editions remain available');
const story=read('components/unfolding-story.tsx');
assert.ok(story.indexOf('A different interest · 1 September 2026')<story.indexOf('id="story-tidemark-sibling"'));
assert.ok(story.includes('id="story-charter-wording"'));
assert.ok(story.includes('data-story-return="story-spending-test" href="/charter#charter-movement-one"'));
assert.ok(story.includes('<time dateTime={scene.occurredAt}>{scene.dateLabel}</time>'));
const returns=read('public/reading-return.js');
assert.ok(!returns.includes('.charter-reader > nav a:first-child'),'Never hijack the charter’s sound-instrument link');
assert.ok(returns.includes('entry.disclosures||[]')&&returns.includes('node=link;node;node=node.parentElement'),'Restore source disclosures, including unnamed nested details');
assert.ok(returns.includes('link.focus({preventScroll:true})')&&returns.includes('link.getBoundingClientRect().top-entry.top'),'Restore focus and original viewport offset');
assert.ok(read('components/site-masthead.tsx').includes("pathname==='/charter'&&<a className=\"contextual-reading-return\" href=\"/#story-alienate\" data-return-link>Back to the story</a>"),'A direct charter visit also has a visible Back fallback');
const contents=read('components/site-contents.tsx');
assert.ok(contents.includes("['Alienate’s charter', '/charter']"));
assert.ok(contents.indexOf('aria-label="Glossary and changelog"')>contents.indexOf('aria-label="Reference and contact"'));
assert.ok(contents.includes('help?.show(null,trigger.current)'),'Use the existing glossary and return focus to Contents');
assert.ok(contents.includes('<a href="/changelog" onClick={()=>dialog.current?.close()}>Changelog</a>'),'Changelog navigation is not swallowed');
console.log('PASS: ordered, dated story scenes; source-return disclosure/focus contracts; charter and Contents access.');
