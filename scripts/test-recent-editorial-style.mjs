import assert from 'node:assert/strict';
import fs from 'node:fs';
import {execFileSync} from 'node:child_process';
import vm from 'node:vm';
import ts from 'typescript';
import {presentEditions,storyPresent} from '../lib/story-present.ts';
import {attemptHistory} from '../lib/attempt-history.ts';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const publishedBaseline='b8fd744bb5dc5d2e0da31f0b774a80560a044f01';
const oldSource=execFileSync('git',['show',`${publishedBaseline}:lib/story-present.ts`],{encoding:'utf8'});
const sandbox={exports:{}};
vm.runInNewContext(ts.transpileModule(oldSource,{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,sandbox);
const previous=JSON.parse(JSON.stringify(sandbox.exports.presentEditions));
assert.deepEqual(JSON.parse(JSON.stringify(presentEditions.slice(0,previous.length))),previous,'Published dated editions remain unchanged');
assert.equal(storyPresent,presentEditions.at(-1));
assert.equal(storyPresent.asOf,'2026-09-09');
assert.match(storyPresent.compactSummary,/No art purchase/);
assert.doesNotMatch(storyPresent.compactSummary,/tomorrow|today|tonight/i);
assert.match(storyPresent.compactSummary,/10 September/);
assert.equal(attemptHistory.at(-1).date,storyPresent.asOf,'Attempt history reaches the admitted current edition');
assert.match(storyPresent.scenes[0].body,/not a binding vote/);
assert.match(storyPresent.scenes[1].body,/charter says no purchase proceeds/);
for(const source of storyPresent.sourceFiles)assert.ok(fs.existsSync(new URL('../public/records/'+source,import.meta.url)));
for(const [id,commentId] of [['story-treasury-debate',50454],['story-spending-test',48478],['story-shared-town',50258],['story-fiction-museum',50259]])assert.equal(storyPresent.scenes.find(s=>s.id===id).commentId,commentId,'Preserve cited passage');
assert.match(read('components/board-agent-name.tsx'),/afterword\|municipal-moth/);
assert.match(read('components/unfolding-story.css'),/data-voice=municipal-moth\]\{background:var\(--voice-board-agent\)/);
assert.equal(JSON.parse(read('public/records/editorial-update-2026-09-09.json')).observed_at,'2026-09-10T00:00:28Z');
const editionTime=read('lib/site-update-times.ts').match(/siteUpdatedAt = '([^']+)'/)?.[1];
assert.ok(editionTime && Date.parse(editionTime)>=Date.parse('2026-09-10T00:01:56Z'),'Site edition time must not move backward');
assert.equal(read('lib/correspondence-notice.ts'),execFileSync('git',['show',`${publishedBaseline}:lib/correspondence-notice.ts`],{encoding:'utf8'}),'Accepted notice unchanged');
console.log('PASS: published editions, source dates, exact comment targets and notice preserved; new status/history, labels and color token consistent.');
